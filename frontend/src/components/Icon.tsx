/**
 * The few icons the dashboard needs, drawn inline: the project has no icon library and a second dependency for
 * twenty small shapes is not worth it. They take their colour from the text (currentColor), so every theme and
 * state colours them without extra rules, and they are hidden from screen readers: the control around them
 * carries the label. The chevron mirrors in right-to-left layouts.
 */
export function Icon({ name, size = 20, className }: { name: IconName; size?: number; className?: string }) {
  return (
    <svg
      className={`icon${name === 'chevron' ? ' icon--directional' : ''}${className ? ` ${className}` : ''}`}
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth="1.8"
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
    >
      {PATHS[name]}
    </svg>
  )
}
